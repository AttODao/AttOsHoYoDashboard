#!/usr/bin/env bash
# Regenerate the self-hosted Noto Sans JP subset from the official OFL variable font.
#
# Source (google/fonts, pinned commit):
#   https://raw.githubusercontent.com/google/fonts/47d54ca1ebb14fd864695f1d39dc734f39017c33/ofl/notosansjp/NotoSansJP%5Bwght%5D.ttf
#   SHA-256 c2f3b4d463500a2ddcd3849cded1fceeb9fd6d1c32e6cbecd568453ba50fc68f
#
# Download it into its own empty directory, then run this script with fontTools
# and brotli available, without installing anything user-wide:
#   nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [p.fonttools p.brotli])' \
#     -c scripts/subset-fonts.sh /path/to/NotoSansJP[wght].ttf
#
# The subset covers every character of dashboard-ui/locales/*.json, the UI Rust
# sources and printable ASCII. The wght axis is limited to 400–700 (the
# @font-face range) and default layout features are kept. Output is named by
# the first 12 hex digits of its SHA-256; update the references printed at the end.
# dashboard-ui/assets/fonts/noto-sans-jp.chars.txt lists the subset's cmap and is
# checked by the UI unit tests against the locale catalogs.
set -euo pipefail
source_font=${1:?usage: subset-fonts.sh <NotoSansJP[wght].ttf>}
expected=c2f3b4d463500a2ddcd3849cded1fceeb9fd6d1c32e6cbecd568453ba50fc68f
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
ui="$root/dashboard-ui"
fonts="$ui/assets/fonts"

actual=$(sha256sum "$source_font" | cut -d' ' -f1)
[[ "$actual" == "$expected" ]] || { echo "Unexpected source SHA-256: $actual" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
# Run Python from the empty work directory with -I so nothing near the inputs is imported.
cd "$work"
# Fixed timestamps make the output, and therefore its name, reproducible.
export SOURCE_DATE_EPOCH=0

python3 -I - "$work/text.txt" "$ui/locales/ja.json" "$ui/locales/en.json" \
    $(find "$ui/src" -name '*.rs' | sort) <<'PY'
import sys
chars = {chr(c) for c in range(0x20, 0x7F)}
for path in sys.argv[2:]:
    with open(path, encoding="utf-8") as source:
        chars.update(ch for ch in source.read() if ch.isprintable())
with open(sys.argv[1], "w", encoding="utf-8") as out:
    out.write("".join(sorted(chars)))
PY

python3 -I -m fontTools.varLib.instancer "$source_font" wght=400:400:700 -o "$work/instance.ttf"
python3 -I -m fontTools.subset "$work/instance.ttf" \
    --text-file="$work/text.txt" --flavor=woff2 --output-file="$work/subset.woff2"

hash=$(sha256sum "$work/subset.woff2" | cut -c1-12)
name="noto-sans-jp-$hash.woff2"
find "$fonts" -maxdepth 1 -regextype posix-extended \
    -regex '.*/noto-sans-jp-[0-9a-f]{12}\.woff2' ! -name "$name" -delete
cp "$work/subset.woff2" "$fonts/$name"

python3 -I - "$fonts/$name" "$fonts/noto-sans-jp.chars.txt" <<'PY'
import sys
from fontTools.ttLib import TTFont
codepoints = sorted(TTFont(sys.argv[1]).getBestCmap())
name = sys.argv[1].rsplit("/", 1)[-1]
with open(sys.argv[2], "w", encoding="utf-8") as out:
    out.write(f"# Generated by scripts/subset-fonts.sh from {name}; do not edit.\n")
    out.writelines(f"U+{cp:04X}\n" for cp in codepoints)
PY

echo "Wrote $name ($(stat -c %s "$fonts/$name") bytes)"
echo "Update references: git grep -n 'noto-sans-jp-[0-9a-f]\{12\}'"
